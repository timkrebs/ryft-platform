// The Content-Security-Policy for the site, from the inline scripts of the built pages.
import { cspHash } from './html.mjs';

/** The policy: scripts only by hash, everything else only from this origin, nothing framed. */
export function policy(hashes) {
  return [
    "default-src 'none'",
    `script-src ${hashes.length ? hashes.join(' ') : "'none'"}`,
    "style-src 'self'",
    "img-src 'self'",
    "font-src 'self'",
    "manifest-src 'self'",
    "connect-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
    "require-trusted-types-for 'script'",
    'upgrade-insecure-requests',
  ].join('; ');
}

/** Sorted, unique hashes of the inline script bodies across pages. */
export function hashesOf(bodies) {
  return [...new Set(bodies.map(cspHash))].sort();
}

/** The nginx snippet. Single quotes in the policy are fine inside nginx's double quotes. */
export function nginxSnippet(hashes, pages) {
  return [
    '# Generated by scripts/csp.mjs from out/ — do not edit. Rebuild to regenerate.',
    `# ${hashes.length} inline script hash(es) across ${pages} page(s).`,
    `add_header Content-Security-Policy "${policy(hashes)}" always;`,
    '',
  ].join('\n');
}
