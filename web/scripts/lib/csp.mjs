// The Content-Security-Policies for the site, from the inline scripts of the built pages.
// Two policies, never combined in one response (two CSP headers intersect, and the marketing
// policy's connect-src 'none' would then win): the marketing one for every page, and the
// admin page's own (web D15).
import { cspHash } from './html.mjs';

/** The marketing policy: no script (web D19; a hash only if one appears), everything else only from this origin, nothing framed. */
export function policy(hashes) {
  return [
    "default-src 'none'",
    `script-src ${hashes.length ? hashes.join(' ') : "'none'"}`,
    "style-src 'self'",
    "img-src 'self'",
    "font-src 'self'",
    "manifest-src 'self'",
    "connect-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
    "require-trusted-types-for 'script'",
    'upgrade-insecure-requests',
  ].join('; ');
}

/** An https origin (scheme and host, optional port) and nothing else; returns it normalised. */
export function httpsOrigin(value, what) {
  if (/[*\s]/.test(value))
    throw new Error(`${what}: ${JSON.stringify(value)} must not contain wildcards or spaces`);
  let u;
  try {
    u = new URL(value);
  } catch {
    throw new Error(`${what}: ${JSON.stringify(value)} is not a URL`);
  }
  if (u.protocol !== 'https:' || u.origin !== value || u.username || u.password) {
    throw new Error(
      `${what}: ${JSON.stringify(value)} must be a bare https origin (no path, no trailing slash)`,
    );
  }
  return u.origin;
}

/**
 * The admin page's policy. Like the marketing one, but: connect-src is path-scoped to what the
 * page uses: the project's Auth API (`<supabase>/auth/v1/`) and the api's admin routes
 * (`<api>/v1/admin/`), so no PostgREST, no storage, no realtime and no user route (`/v1/me`)
 * is reachable from it; no 'self', no wss:. A source path ending in "/" is a prefix match.
 * img-src gains data: for the TOTP QR code (an SVG in an <img> runs no script), and Trusted
 * Types is 'none' (the page has no HTML sink). `config` is config/admin.json, the same file
 * the bundle is built from.
 */
export function adminPolicy(hashes, config) {
  const api = httpsOrigin(config.apiUrl, 'config/admin.json apiUrl');
  const supabase = httpsOrigin(config.supabaseUrl, 'config/admin.json supabaseUrl');
  return [
    "default-src 'none'",
    `script-src ${hashes.length ? hashes.join(' ') : "'none'"}`,
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src ${supabase}/auth/v1/ ${api}/v1/admin/`,
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
    "require-trusted-types-for 'script'",
    "trusted-types 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

/** Sorted, unique hashes of the inline script bodies across pages. */
export function hashesOf(bodies) {
  return [...new Set(bodies.map(cspHash))].sort();
}

/** The nginx snippet. Single quotes in the policy are fine inside nginx's double quotes. */
export function nginxSnippet(hashes, pages) {
  return snippet(policy(hashes), hashes, pages);
}

/** The admin page's snippet (nginx/csp-admin.conf). */
export function adminNginxSnippet(hashes, config) {
  return snippet(adminPolicy(hashes, config), hashes, 1);
}

function snippet(csp, hashes, pages) {
  return [
    '# Generated by scripts/csp.mjs from out/ — do not edit. Rebuild to regenerate.',
    `# ${hashes.length} inline script hash(es) across ${pages} page(s).`,
    `add_header Content-Security-Policy "${csp}" always;`,
    '',
  ].join('\n');
}
