#!/usr/bin/env node
// Read-only brand report for the sibling repositories: runs the brand matcher over every
// tracked text file of ../app and ../plattform (and the shared docs at the root) and
// writes docs/BRAND_CHECK.md, split into "user-facing — must change" and "internal docs
// and comments — user decides". Never writes outside web/. Matches are masked.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { isMarkupPath, isTextPath, loadDenylist, redact, scanText } from './lib/brand.mjs';

const ROOT = resolve(import.meta.dirname, '..');
const RYFT = resolve(ROOT, '..');
const denylist = loadDenylist();
const today = new Date().toISOString().slice(0, 10);

/** What a person outside the team reads: app UI, App Store and TestFlight text, push, insights, the site. */
const USER_FACING = [
  /^app\/.*\.xcstrings$/,
  /^app\/.*Info\.plist$/,
  /^app\/docs\/APP_STORE\.md$/,
  /^app\/docs\/TESTFLIGHT[^/]*\.md$/,
  /^app\/(Ryft|RyftWidgets|RyftNotificationService)\/.*\.swift$/,
  /^plattform\/backend\/internal\/(insights|notify|behavior)\/.*\.go$/,
  /^plattform\/backend\/internal\/scoring\/changelog\.json$/,
  /^plattform\/backend\/cmd\/api\/push\.go$/,
  /^plattform\/deploy\/k8s\/base\/web\//,
  /^plattform\/docs\/API\.md$/,
];
const CODE = /\.(swift|go)$/;

const files = [
  ...tracked('app'),
  ...tracked('plattform'),
  ...['README.md', 'ROADMAP.md'].filter((f) => existsSync(join(RYFT, f))),
  ...walk(join(RYFT, 'docs')).map((p) => relative(RYFT, p)),
];

const userFacing = [];
const internal = [];
for (const rel of files) {
  const nameHits = scanText(rel, denylist).filter((f) => f.level === 'hard');
  if (nameHits.length) internal.push({ rel, line: 0, id: 'file-name', context: '(the file name itself)' });
  if (!isTextPath(rel)) continue;
  const abs = join(RYFT, rel);
  if (!existsSync(abs) || statSync(abs).size > 5 * 1024 * 1024) continue;
  const text = readFileSync(abs, 'utf8');
  const lines = text.split(/\r?\n/);
  const fences = fencedLines(lines);
  for (const f of scanText(text, denylist, { file: rel, markup: isMarkupPath(rel) })) {
    const line = lines[f.line - 1] ?? '';
    const facing =
      USER_FACING.some((re) => re.test(rel)) &&
      !(CODE.test(rel) && isComment(line)) &&
      !(rel.endsWith('API.md') && !fences.has(f.line));
    (facing ? userFacing : internal).push({ rel, line: f.line, id: f.id, level: f.level, context: line });
  }
}

writeFileSync(join(ROOT, 'docs/BRAND_CHECK.md'), render());
console.log(
  `brand report: ${userFacing.length} user-facing and ${internal.length} internal finding(s) → docs/BRAND_CHECK.md`,
);

function render() {
  const row = (h) => `| \`${maskPath(h.rel)}${h.line ? `:${h.line}` : ''}\` | ${h.id} | ${cell(h.context)} |`;
  const table = (hits) =>
    hits.length
      ? ['| Where | Rule | Line (match masked) |', '| --- | --- | --- |', ...hits.map(row)].join('\n')
      : '_None._';
  const hard = (hits) => hits.filter((h) => h.level !== 'warn');
  const warn = (hits) => hits.filter((h) => h.level === 'warn');
  return `# Brand check — app and platform

Generated by \`npm run brand:report\` (scripts/brand-report.mjs) on ${today}: the rules in
\`config/brand-denylist.json\`, read-only over every tracked text file of \`../app\` and
\`../plattform\` and the shared docs at the root. Nothing outside \`web/\` was changed. Every
match is masked (▇), so this file never repeats it. Line numbers are as of ${today}; run the
script again after changes.

- **User-facing** — what testers, App Review or users read: string catalogs, Info.plist, App
  Store and TestFlight texts, Swift string literals, insight and push copy, the scoring
  changelog, the old web drafts and the JSON examples in \`docs/API.md\`. **Must change.**
- **Internal** — comments, design notes, roadmap, research. **The user decides**; the rule
  for the website is stricter than for internal notes, but a public repository counts:
  \`timkrebs/ryft-app\` and \`timkrebs/ryft-platform\` are public (checked 2026-10-20), so their
  internal files are readable by anyone. The most visible is \`plattform/README.md\`, the
  platform repository's front page on GitHub.

## User-facing — must change (${hard(userFacing).length})

${table(hard(userFacing))}

### Warnings in user-facing text (${warn(userFacing).length})

Comparison phrases and borrowed feature names (see the denylist's warn rules).

${table(warn(userFacing))}

## Internal docs and comments — user decides (${hard(internal).length})

${table(hard(internal))}

### Warnings in internal text (${warn(internal).length})

${table(warn(internal))}
`;
}

function cell(text) {
  return redact(text, denylist).trim().replace(/\|/g, '\\|').replace(/`/g, "'").slice(0, 160);
}

function maskPath(p) {
  return redact(p, denylist);
}

function isComment(line) {
  return /^\s*(\/\/|\/\*|\*|#)/.test(line);
}

function fencedLines(lines) {
  const inside = new Set();
  let open = false;
  lines.forEach((l, i) => {
    if (/^\s*```/.test(l)) open = !open;
    else if (open) inside.add(i + 1);
  });
  return inside;
}

function tracked(dir) {
  const abs = join(RYFT, dir);
  if (!existsSync(abs)) return [];
  return execFileSync('git', ['-C', abs, 'ls-files', '-z'], { encoding: 'utf8', maxBuffer: 64 << 20 })
    .split('\0')
    .filter(Boolean)
    .map((f) => `${dir}/${f}`);
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
  );
}
