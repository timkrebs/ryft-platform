// Package logx is the services' structured logging: JSON lines on stdout,
// every line carrying the service name and — when logged with a request's
// context (InfoContext etc.) — its request_id, user_id and route, so one
// request can be followed across ingest, the broker and scoring.
//
// Tokens, emails and request bodies are never logged.
package logx

import (
	"context"
	"io"
	"log/slog"
	"net/http"
	"os"
	"strconv"
	"strings"
)

// StatusLine is an HTTP status as a log line or an error may hold it: the code
// and the standard phrase, "unknown status" for a code net/http has none for
// (520). Never resp.Status, whose text is the server's.
func StatusLine(code int) string {
	text := http.StatusText(code)
	if text == "" {
		text = "unknown status"
	}
	return strconv.Itoa(code) + " " + text
}

// Fields are the per-request values every log line carries. The outermost
// HTTP middleware creates them; inner layers fill in what they learn (the
// route once matched, the user once authenticated). They travel as a pointer
// because middleware hands copies of the request inward.
type Fields struct {
	RequestID       string // generated by us for every request
	ClientRequestID string // X-Request-ID the client sent, if any (not trusted)
	UserID          string
	Route           string // ServeMux pattern, e.g. "GET /v1/days/{day}"
	// The answer's error code (model.Code*) or, for a 401 or an auth 503, the
	// reason; only the access line carries it.
	Code string
}

type fieldsKey struct{}

// NewContext attaches fresh Fields to ctx.
func NewContext(ctx context.Context) (context.Context, *Fields) {
	f := &Fields{}
	return context.WithValue(ctx, fieldsKey{}, f), f
}

// WithFields attaches the given Fields (e.g. rebuilt from an event).
func WithFields(ctx context.Context, f *Fields) context.Context {
	return context.WithValue(ctx, fieldsKey{}, f)
}

// FieldsFrom returns the context's Fields, or nil.
func FieldsFrom(ctx context.Context) *Fields {
	f, _ := ctx.Value(fieldsKey{}).(*Fields)
	return f
}

// New returns a JSON logger for service at level.
func New(service string, level slog.Level) *slog.Logger {
	return NewWriter(os.Stdout, service, level)
}

// NewWriter is New with a custom destination (tests).
func NewWriter(w io.Writer, service string, level slog.Level) *slog.Logger {
	h := slog.NewJSONHandler(w, &slog.HandlerOptions{Level: level})
	return slog.New(contextHandler{h}).With("service", service)
}

// ParseLevel maps LOG_LEVEL (debug, info, warn, error) to a level; anything
// else is info.
func ParseLevel(s string) slog.Level {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "debug":
		return slog.LevelDebug
	case "warn", "warning":
		return slog.LevelWarn
	case "error":
		return slog.LevelError
	default:
		return slog.LevelInfo
	}
}

// contextHandler adds the context's Fields to every record.
type contextHandler struct{ slog.Handler }

func (h contextHandler) Handle(ctx context.Context, r slog.Record) error {
	if f := FieldsFrom(ctx); f != nil {
		if f.RequestID != "" {
			r.AddAttrs(slog.String("request_id", f.RequestID))
		}
		if f.ClientRequestID != "" {
			r.AddAttrs(slog.String("client_request_id", f.ClientRequestID))
		}
		if f.UserID != "" {
			r.AddAttrs(slog.String("user_id", f.UserID))
		}
		if f.Route != "" {
			r.AddAttrs(slog.String("route", f.Route))
		}
	}
	return h.Handler.Handle(ctx, r)
}

func (h contextHandler) WithAttrs(attrs []slog.Attr) slog.Handler {
	return contextHandler{h.Handler.WithAttrs(attrs)}
}

func (h contextHandler) WithGroup(name string) slog.Handler {
	return contextHandler{h.Handler.WithGroup(name)}
}
