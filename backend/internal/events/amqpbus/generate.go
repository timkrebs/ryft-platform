// Definitions is t in RabbitMQ's definitions format (what the management API and
// load_definitions import), for compose and the tests. users maps each user to its
// password; "admin" gets the administrator tag and every right (compose's operator,
// like the operator's default user on the cluster).
func Definitions(t Topology, users map[string]string) map[string]any {
	type obj = map[string]any
	var us, perms, topics []obj
	names := make([]string, 0, len(users))
	for n := range users {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		tags := []string{}
		if n == "admin" {
			tags = []string{"administrator"}
			perms = append(perms, obj{"user": n, "vhost": Vhost, "configure": ".*", "write": ".*", "read": ".*"})
		}
		us = append(us, obj{"name": n, "password": users[n], "tags": tags})
	}
	for _, g := range t.Grants {
		perms = append(perms, obj{"user": g.User, "vhost": Vhost, "configure": "^$",
			"write": ResourceRegex(g.Write), "read": ResourceRegex(g.Read)})
		for _, ex := range sortedKeys(g.Topics) {
			topics = append(topics, obj{"user": g.User, "vhost": Vhost, "exchange": ex, "write": g.Topics[ex], "read": "^$"})
		}
	}
	d := VhostDefinitions(t)
	d["users"] = us
	d["vhosts"] = []obj{{"name": Vhost, "default_queue_type": "quorum"}}
	d["permissions"] = perms
	d["topic_permissions"] = topics
	return d
}

// VhostDefinitions is t's exchanges, queues, bindings and policies only: what the
// management API imports into one vhost (POST /api/definitions/{vhost}), which the
// integration tests do into a fresh vhost each.
func VhostDefinitions(t Topology) map[string]any {
	type obj = map[string]any
	var ex, qs, bs, ps []obj
	for _, e := range t.Exchanges {
		ex = append(ex, obj{"name": e.Name, "vhost": Vhost, "type": e.Type, "durable": true, "auto_delete": false,
			"internal": false, "arguments": obj{}})
	}
	for _, q := range t.Queues {
		qs = append(qs, obj{"name": q.Name, "vhost": Vhost, "durable": true, "auto_delete": false,
			"arguments": obj{"x-queue-type": "quorum"}})
	}
	for _, b := range t.Bindings {
		bs = append(bs, obj{"source": b.Source, "vhost": Vhost, "destination": b.Destination, "destination_type": "queue",
			"routing_key": b.Key, "arguments": obj{}})
	}
	for _, p := range t.Policies {
		ps = append(ps, obj{"vhost": Vhost, "name": p.Name, "pattern": p.Pattern, "apply-to": "quorum_queues",
			"priority": p.Priority, "definition": p.Definition})
	}
	return obj{"exchanges": ex, "queues": qs, "bindings": bs, "policies": ps}
}

// CRs is t as Topology Operator objects for the RabbitmqCluster ClusterName, in sync
// waves after the cluster (wave 1): the vhost, then exchanges, queues and users, then
// what refers to them. Users take their credentials from Secret amqp-user-<user>
// (keys username and password), which the Vault Secrets Operator writes.
func CRs(t Topology) string {
	var b strings.Builder
	b.WriteString("# Generated by `go run ./cmd/rabbitmq-topology` from internal/events/amqpbus/topology.go;\n" +
		"# do not edit (make k8s-validate fails when it differs). D99.\n")
	doc := func(kind, name, wave string, spec map[string]any) {
		spec["rabbitmqClusterReference"] = map[string]any{"name": ClusterName}
		fmt.Fprintf(&b, "---\napiVersion: rabbitmq.com/v1beta1\nkind: %s\nmetadata:\n  name: %s\n  annotations:\n    argocd.argoproj.io/sync-wave: %q\nspec:\n",
			kind, name, wave)
		writeYAML(&b, spec, 1)
	}
	doc("Vhost", Vhost, "2", map[string]any{"name": Vhost, "defaultQueueType": "quorum", "deletionPolicy": "retain"})
	for _, e := range t.Exchanges {
		doc("Exchange", e.Name, "3", map[string]any{"name": e.Name, "vhost": Vhost, "type": e.Type, "durable": true, "autoDelete": false})
	}
	for _, q := range t.Queues {
		doc("Queue", q.Name, "3", map[string]any{"name": q.Name, "vhost": Vhost, "type": "quorum", "durable": true,
			"autoDelete": false, "deletionPolicy": "retain"})
	}
	for _, g := range t.Grants {
		doc("User", g.User, "3", map[string]any{"tags": []string{}, "importCredentialsSecret": map[string]any{"name": "amqp-user-" + g.User}})
	}
	for _, x := range t.Bindings {
		doc("Binding", x.Source+"--"+x.Destination+"--"+x.Key, "4", map[string]any{"vhost": Vhost, "source": x.Source,
			"destination": x.Destination, "destinationType": "queue", "routingKey": x.Key})
	}
	for _, p := range t.Policies {
		doc("Policy", p.Name, "4", map[string]any{"name": p.Name, "vhost": Vhost, "pattern": p.Pattern,
			"applyTo": "quorum_queues", "priority": p.Priority, "definition": p.Definition})
	}
	for _, g := range t.Grants {
		doc("Permission", g.User, "4", map[string]any{"vhost": Vhost, "userReference": map[string]any{"name": g.User},
			"permissions": map[string]any{"configure": "^$", "write": ResourceRegex(g.Write), "read": ResourceRegex(g.Read)}})
		for _, ex := range sortedKeys(g.Topics) {
			doc("TopicPermission", g.User+"--"+ex, "4", map[string]any{"vhost": Vhost, "userReference": map[string]any{"name": g.User},
				"permissions": map[string]any{"exchange": ex, "write": g.Topics[ex], "read": "^$"}})
		}
	}
	return b.String()
}

// writeYAML writes v (maps, slices, scalars) as block YAML, keys sorted.
func writeYAML(b *strings.Builder, v any, depth int) {
	ind := strings.Repeat("  ", depth)
	switch x := v.(type) {
	case map[string]any:
		for _, k := range sortedKeys(x) {
			switch val := x[k].(type) {
			case map[string]any:
				if len(val) == 0 {
					fmt.Fprintf(b, "%s%s: {}\n", ind, k)
					continue
				}
				fmt.Fprintf(b, "%s%s:\n", ind, k)
				writeYAML(b, val, depth+1)
			case []string:
				if len(val) == 0 {
					fmt.Fprintf(b, "%s%s: []\n", ind, k)
					continue
				}
				fmt.Fprintf(b, "%s%s:\n", ind, k)
				for _, s := range val {
					fmt.Fprintf(b, "%s  - %s\n", ind, scalar(s))
				}
			default:
				fmt.Fprintf(b, "%s%s: %s\n", ind, k, scalar(val))
			}
		}
	}
}

// scalar is a YAML scalar; strings are JSON-quoted (valid YAML, exact for regexes).
func scalar(v any) string {
	switch x := v.(type) {
	case string:
		q, _ := json.Marshal(x)
		return string(q)
	default:
		return fmt.Sprint(x)
	}
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
