// The files cmd/pubsub-topology writes, relative to the repository root.
const (
	TFVarsFile       = "infra/gcp/pubsub.auto.tfvars.json"
	EmulatorInitFile = "deploy/pubsub-emulator/init.sh"
)

// The entries of the tfvars, with the field order infra/gcp reads (ticket B → The
// topology tfvars): encoding/json writes a struct's fields in declaration order.
type tfTopic struct {
	Publishers []string `json:"publishers"`
}

type tfPush struct {
	Topic                   string `json:"topic"`
	Service                 string `json:"service"`
	Path                    string `json:"path"`
	Ordered                 bool   `json:"ordered"`
	AckDeadlineSeconds      int64  `json:"ack_deadline_seconds"`
	MessageRetentionSeconds int64  `json:"message_retention_seconds"`
	DeadLetterTopic         string `json:"dead_letter_topic"`
}

type tfHold struct {
	Topic                   string `json:"topic"`
	MessageRetentionSeconds int64  `json:"message_retention_seconds"`
}

// TFVars is infra/gcp/pubsub.auto.tfvars.json: MarshalIndent with two spaces and one
// newline. The top level and the three collections are maps, so their keys come out
// sorted; publishers are sorted and [] when empty, never null.
func TFVars(t Topology) ([]byte, error) {
	topics := map[string]tfTopic{}
	for _, x := range t.Topics {
		p := slices.Sorted(slices.Values(x.Publishers))
		if p == nil {
			p = []string{}
		}
		topics[x.Name] = tfTopic{Publishers: p}
	}
	push := map[string]tfPush{}
	for _, s := range t.Push {
		push[s.Name] = tfPush{Topic: s.Topic, Service: s.Service, Path: s.Path, Ordered: s.Ordered,
			AckDeadlineSeconds: seconds(s.AckDeadline), MessageRetentionSeconds: seconds(s.Retention), DeadLetterTopic: s.DeadLetterTopic}
	}
	hold := map[string]tfHold{}
	for _, h := range t.Hold {
		hold[h.Name] = tfHold{Topic: h.Topic, MessageRetentionSeconds: seconds(h.Retention)}
	}
	b, err := json.MarshalIndent(map[string]any{
		"pubsub_topics":             topics,
		"pubsub_push_subscriptions": push,
		"pubsub_hold_subscriptions": hold,
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

func seconds(d time.Duration) int64 { return int64(d / time.Second) }

// EmulatorInit is deploy/pubsub-emulator/init.sh: POSIX sh and curl that create the
// topology on the emulator at $PUBSUB_EMULATOR_HOST in project $GCP_PROJECT, with the
// push endpoints compose's services listen on and the delivery policy Terraform sets. A
// topic or subscription that exists already (409) is kept, so a rerun is harmless.
func EmulatorInit(t Topology) []byte {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w(`#!/bin/sh
# Generated by `+"`go run ./cmd/pubsub-topology`"+` (in backend/) from
# backend/internal/events/pubsub/topology.go. DO NOT EDIT: change the Go and regenerate.
#
# Creates the Pub/Sub topology on the emulator: the topics, the push subscriptions to
# compose's services (http://<service>:8080<path>) with the retry and dead-letter policy
# Terraform sets (infra/gcp/pubsub.tf), and the dead-letter hold subscriptions (pull).
# Idempotent: what exists already (HTTP 409) is kept as it is, so a rerun on a running
# emulator is fine. The emulator checks no IAM and no OIDC token.
#
# Usage: PUBSUB_EMULATOR_HOST=pubsub:8085 [GCP_PROJECT=%[1]s] sh init.sh
set -eu

: "${PUBSUB_EMULATOR_HOST:?set PUBSUB_EMULATOR_HOST to the emulator's host:port}"
: "${GCP_PROJECT:=%[1]s}"
base="http://${PUBSUB_EMULATOR_HOST}/v1/projects/${GCP_PROJECT}"

# Wait up to 60 s for the emulator to answer.
i=0
until curl -s -o /dev/null "http://${PUBSUB_EMULATOR_HOST}/"; do
  i=$((i + 1))
  if [ "$i" -ge 60 ]; then
    echo "init.sh: the emulator at ${PUBSUB_EMULATOR_HOST} does not answer" >&2
    exit 1
  fi
  sleep 1
done

# put <path> <json>: 200 created, 409 exists already; anything else stops the script.
put() {
  code=$(curl -s -o /dev/null -w '%%{http_code}' -X PUT -H 'Content-Type: application/json' --data "$2" "${base}/$1") || code=000
  case "$code" in
    200) echo "created $1" ;;
    409) echo "exists  $1" ;;
    *) echo "init.sh: PUT $1 answered HTTP $code" >&2; exit 1 ;;
  esac
}

topic() {
  put "topics/$1" '{}'
}

# push <subscription> <topic> <service> <path> <ordered> <ack deadline s> <retention s> [<dead-letter topic>]
# The push endpoint is http://<service>:8080<path>, where compose's service listens.
push() {
  dlq=""
  if [ -n "${8:-}" ]; then
    dlq=$(printf ',"deadLetterPolicy":{"deadLetterTopic":"projects/%%s/topics/%%s","maxDeliveryAttempts":%[2]d}' "$GCP_PROJECT" "$8")
  fi
  put "subscriptions/$1" "$(printf '{"topic":"projects/%%s/topics/%%s","pushConfig":{"pushEndpoint":"http://%%s:8080%%s"},"enableMessageOrdering":%%s,"ackDeadlineSeconds":%%s,"messageRetentionDuration":"%%ss","retryPolicy":{"minimumBackoff":"%[3]ds","maximumBackoff":"%[4]ds"}%%s}' \
    "$GCP_PROJECT" "$2" "$3" "$4" "$5" "$6" "$7" "$dlq")"
}

# hold <subscription> <topic> <retention s>: a pull subscription.
hold() {
  put "subscriptions/$1" "$(printf '{"topic":"projects/%%s/topics/%%s","ackDeadlineSeconds":%[5]d,"messageRetentionDuration":"%%ss"}' \
    "$GCP_PROJECT" "$2" "$3")"
}

`, config.EmulatorProject, MaxDeliveryAttempts, seconds(RetryMinimumBackoff), seconds(RetryMaximumBackoff), seconds(HoldAckDeadline))
	topics := slices.Clone(t.Topics)
	slices.SortFunc(topics, func(a, b Topic) int { return strings.Compare(a.Name, b.Name) })
	for _, x := range topics {
		w("topic %s\n", x.Name)
	}
	w("\n")
	push := slices.Clone(t.Push)
	slices.SortFunc(push, func(a, b PushSubscription) int { return strings.Compare(a.Name, b.Name) })
	for _, s := range push {
		w("push %s %s %s %s %t %d %d", s.Name, s.Topic, s.Service, s.Path, s.Ordered, seconds(s.AckDeadline), seconds(s.Retention))
		if s.DeadLetterTopic != "" {
			w(" %s", s.DeadLetterTopic)
		}
		w("\n")
	}
	w("\n")
	hold := slices.Clone(t.Hold)
	slices.SortFunc(hold, func(a, b HoldSubscription) int { return strings.Compare(a.Name, b.Name) })
	for _, h := range hold {
		w("hold %s %s %d\n", h.Name, h.Topic, seconds(h.Retention))
	}
	return []byte(b.String())
}
