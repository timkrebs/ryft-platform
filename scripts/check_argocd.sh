#!/usr/bin/env bash
# Part of make k8s-validate (offline): every Argo CD application in deploy/argocd/apps
# reads this repository, belongs to a project in deploy/argocd/project.yaml, deploys
# into a namespace that project admits, and points at a path that renders. Only a
# vault-namespaces directory may be missing: infra/vault writes it on its first apply
# after a service is added (docs/OPERATIONS.md → Adding a service).
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - <<'PY'
import glob, re, subprocess, sys
repo = "https://github.com/timkrebs/ryft-platform.git"
def field(doc, key):
    m = re.search(rf"^\s*{key}:\s*(\S+)\s*$", doc, re.M)
    return m.group(1).strip('"') if m else None
projects = {}
for doc in open("deploy/argocd/project.yaml").read().split("\n---\n"):
    name = re.search(r"^metadata:\n(?:\s+.*\n)*?\s+name:\s*(\S+)", doc, re.M)
    if name:
        projects[name.group(1)] = re.findall(r'namespace:\s*"?([^"\s},]+)"?\s*}', doc)
bad, warn = [], []
# Argo's directory source applies *.yaml, *.yml, *.json and *.jsonnet from apps/ (the checks and the
# kubeconform loop in the Makefile read *.yaml only): nothing else may be in that directory.
import os
for e in sorted(os.listdir("deploy/argocd/apps")):
    full = os.path.join("deploy/argocd/apps", e)
    if not (e.endswith(".yaml") and not e.startswith(".") and os.path.isfile(full) and not os.path.islink(full)):
        bad.append(f"{full}: apps/ holds only regular *.yaml files (Argo applies .yml, .json and .jsonnet there too, and nothing else here is checked)")
apps = sorted(glob.glob("deploy/argocd/apps/*.yaml")) + ["deploy/argocd/root.yaml"]
for f in apps:
    doc = open(f).read()
    name, project, path, ns = field(doc, "name"), field(doc, "project"), field(doc, "path"), field(doc, "  namespace")
    dest_ns = re.search(r"destination:\n(?:\s+#.*\n|\s+server:.*\n)*\s+namespace:\s*(\S+)", doc)
    dest_ns = dest_ns.group(1) if dest_ns else ""
    if field(doc, "repoURL") != repo: bad.append(f"{f}: repoURL is not {repo}")
    if project not in projects: bad.append(f"{f}: project {project} is not in project.yaml"); continue
    if not any(re.fullmatch(p.replace("*", ".*"), dest_ns) for p in projects[project]):
        bad.append(f"{f}: destination namespace {dest_ns!r} is not admitted by project {project} ({projects[project]})")
    if "sync-wave" not in doc and f.endswith(".yaml") and "/apps/" in f: bad.append(f"{f}: no sync wave")
    if "/apps/" in f and "ServerSideDiff=true" not in doc: bad.append(f"{f}: no server-side diff (StatefulSets drift without it)")
    import os
    if not os.path.isdir(path):
        (warn if path.startswith("deploy/k8s/overlays/vault-namespaces/") else bad).append(f"{f}: {path} does not exist")
        continue
    if not glob.glob(path + "/kustomization.yaml"): continue  # apps/: plain manifests
    r = subprocess.run(["kubectl", "kustomize", path], capture_output=True, text=True)
    if r.returncode != 0: bad.append(f"{f}: {path} does not render: {r.stderr.strip()[:200]}")
for w in warn: print(f"! check_argocd: {w} (generated by the next infra/vault apply)")
for b in bad: print(f"✗ check_argocd: {b}")
if bad: sys.exit(1)
print(f"✓ {len(apps)} Argo CD applications: this repository, their projects' namespaces, paths that render")
PY
