#!/usr/bin/env bash
# shellcheck disable=SC2016  # the table rows hold backticks on purpose
# scripts/pkgmap.sh on a fixture module (make test-scripts): the table is rendered between the markers and
# nothing else in the file moves; --check is 0 when current, 1 when a row, a doc.go or a test file moved on, and
# 2 when it cannot work (a missing or duplicated marker, no go.mod, a package that does not parse, bad usage).
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
fail() { echo "✗ pkgmap_test: $*" >&2; exit 1; }
BEGIN='<!-- pkgmap:begin: generated by scripts/pkgmap.sh, do not edit -->'
END='<!-- pkgmap:end -->'

mod=$tmp/mod
mkdir -p "$mod/internal/leaf" "$mod/internal/user" "$mod/internal/low" "$mod/internal/emptydir" "$mod/cmd/app"
printf 'module example.test/m\n\ngo 1.21\n' > "$mod/go.mod"
printf '// Package leaf owns the | pipe, which a table cell must escape. More text follows.\npackage leaf\n' > "$mod/internal/leaf/doc.go"
printf 'package leaf\n\nfunc F() int { return 1 }\n' > "$mod/internal/leaf/leaf.go"
printf 'package leaf\n\nimport "testing"\n\nfunc TestF(t *testing.T) { _ = F() }\n' > "$mod/internal/leaf/leaf_test.go"
printf '// Package low is imported by a test only.\npackage low\n' > "$mod/internal/low/doc.go"
printf '// Package user uses leaf.\npackage user\n\nimport "example.test/m/internal/leaf"\n\nvar V = leaf.F()\n' > "$mod/internal/user/doc.go"
printf 'package user_test\n\nimport (\n\t"testing"\n\n\t_ "example.test/m/internal/low"\n)\n\nfunc TestX(t *testing.T) {}\n' > "$mod/internal/user/user_test.go"
printf '// app runs it.\npackage main\n\nimport _ "example.test/m/internal/user"\n\nfunc main() {}\n' > "$mod/cmd/app/doc.go"
printf 'package main\n\nimport "testing"\n\n// RYFT_TEST_POSTGRES_URL gates this one.\nfunc TestY(t *testing.T) {}\n' > "$mod/cmd/app/main_test.go"
printf 'package emptydir_test\n' > "$mod/internal/emptydir/x_test.go" # a test-only directory: no row

doc=$tmp/ARCH.md
printf '# Title\n\nbefore\n\n%s\n%s\n\nafter\n' "$BEGIN" "$END" > "$doc"
run() { PKGMAP_MODULE=$mod PKGMAP_DOC=$doc "$HERE/scripts/pkgmap.sh" "$@" >"$tmp/out" 2>"$tmp/err"; }
rc() { local c=0; run "$@" || c=$?; echo "$c"; }

[ "$(rc)" = 0 ] || fail "write: $(cat "$tmp/err")"
for want in \
  '| `cmd/app` | app runs it. | user | 1 file (Postgres) |' \
  '| `internal/leaf` | owns the \| pipe, which a table cell must escape. | none | 1 file |' \
  '| `internal/low` | is imported by a test only. | none | via user |' \
  '| `internal/user` | uses leaf. | leaf | 1 file |'; do
  grep -qxF -- "$want" "$doc" || fail "row missing: $want
$(cat "$doc")"
done
! grep -q emptydir "$doc" || fail "a test-only directory got a row"
rows=$(grep -c '^| `' "$doc"); [ "$rows" = 4 ] || fail "$rows rows, want 4"
[ "$(sed -n 1,5p "$doc" | tr '\n' '~')" = "# Title~~before~~$BEGIN~" ] || fail "the head of the file moved"
[ "$(tail -n 2 "$doc" | tr '\n' '~')" = "~after~" ] || fail "the tail of the file moved: $(tail -n 2 "$doc")"
grep -qxF "$END" "$doc" || fail "the end marker is gone"

cp "$doc" "$tmp/written.md"
[ "$(rc --check)" = 0 ] || fail "--check on a fresh table: $(cat "$tmp/err")"
[ "$(rc)" = 0 ] || fail "write again"
cmp -s "$doc" "$tmp/written.md" || fail "writing twice changed the file"

# A row edited by hand, a doc.go changed, a test file added: stale (1) with a diff and the way out.
sed 's/| user |/| nothing |/' "$tmp/written.md" > "$doc"
[ "$(rc --check)" = 1 ] || fail "--check on an edited row: $(cat "$tmp/out" "$tmp/err")"
grep -q 'scripts/pkgmap.sh' "$tmp/err" || fail "the failure does not name the script: $(cat "$tmp/err")"
grep -q '^+.*| user |' "$tmp/err" || fail "the failure carries no diff: $(cat "$tmp/err")"
[ "$(rc)" = 0 ] || fail "write after an edited row"
cmp -s "$doc" "$tmp/written.md" || fail "write does not repair an edited row"

printf '// Package leaf owns something else.\npackage leaf\n' > "$mod/internal/leaf/doc.go"
[ "$(rc --check)" = 1 ] || fail "--check after a doc.go change"
[ "$(rc)" = 0 ] || fail "write after a doc.go change"
[ "$(rc --check)" = 0 ] || fail "check after the write"
grep -qF 'owns something else.' "$doc" || fail "the new first sentence is not in the table"

printf 'package leaf\n' > "$mod/internal/leaf/more_test.go"
[ "$(rc --check)" = 1 ] || fail "--check after a test file was added"
[ "$(rc)" = 0 ] || fail "write after a test file was added"
grep -qxF '| `internal/leaf` | owns something else. | none | 2 files |' "$doc" || fail "two test files are not counted: $(cat "$doc")"

# It cannot work: 2, never 0 or 1.
good=$(cat "$doc")
printf 'no markers here\n' > "$doc"
[ "$(rc --check)" = 2 ] || fail "no markers"
[ "$(rc)" = 2 ] || fail "no markers (write)"
printf '%s\n%s\n%s\n%s\n' "$BEGIN" "$END" "$BEGIN" "$END" > "$doc"
[ "$(rc --check)" = 2 ] || fail "duplicated markers"
printf '%s\n%s\n' "$END" "$BEGIN" > "$doc"
[ "$(rc --check)" = 2 ] || fail "markers in the wrong order"
printf '%s\nrows\n' "$BEGIN" > "$doc"
[ "$(rc --check)" = 2 ] || fail "no end marker"
printf '%s\n' "$good" > "$doc"
[ "$(rc --check)" = 0 ] || fail "restoring the file: $(cat "$tmp/err")"
[ "$(rc --fix)" = 2 ] || fail "unknown option"
[ "$(rc --check extra)" = 2 ] || fail "extra argument"
rm "$mod/go.mod"
[ "$(rc --check)" = 2 ] || fail "no go.mod"
printf 'module example.test/m\n\ngo 1.21\n' > "$mod/go.mod"
printf 'package other\n' > "$mod/internal/low/broken.go"
[ "$(rc --check)" = 2 ] || fail "a package that does not parse must read as neither current nor stale: $(cat "$tmp/err")"
rm "$mod/internal/low/broken.go"
doc=$tmp/missing.md
[ "$(rc --check)" = 2 ] || fail "a missing doc file"
echo "✓ pkgmap_test"
