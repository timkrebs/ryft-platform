#!/usr/bin/env bash
# The package map in docs/ARCHITECTURE.md (Package map): one row per Go package of the backend, generated from
# `go list` so it cannot rot. Package, owns (the first sentence of its doc.go, which is go list's .Doc), depends on
# (the direct imports of this module, not the transitive closure) and tested by (its own test files, with the
# external services they need; else the packages whose tests import it).
#   scripts/pkgmap.sh           rewrite the table between the markers in docs/ARCHITECTURE.md
#   scripts/pkgmap.sh --check   change nothing; exit 1 with a diff when the table in the file is stale (CI `lint`
#                               and `make pkgmap-check`)
# Exit 0: current (or written). 1: stale (--check). 2: it cannot work: no go, go list fails, a marker missing or
# duplicated, bad usage. A broken check must not read as "current".
# The file sets are fixed to linux/amd64 without cgo, no go.work and no GOFLAGS (-tags) so the table does not
# depend on the machine. The packages
# come from backend/ only, so the git worktrees under .claude/ never enter the table.
# Env (tests): PKGMAP_MODULE (the directory with go.mod, default backend/), PKGMAP_DOC (the markdown file, default
# docs/ARCHITECTURE.md).
set -euo pipefail

BEGIN_MARK='<!-- pkgmap:begin: generated by scripts/pkgmap.sh, do not edit -->'
END_MARK='<!-- pkgmap:end -->'

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
module_dir=${PKGMAP_MODULE:-$root/backend}
doc=${PKGMAP_DOC:-$root/docs/ARCHITECTURE.md}

die() { echo "pkgmap: $*" >&2; exit 2; }

mode='write'
case "${1:-}" in
  "") ;;
  --check) mode=check ;;
  *) die "usage: scripts/pkgmap.sh [--check]" ;;
esac
[ $# -le 1 ] || die "usage: scripts/pkgmap.sh [--check]"

command -v go >/dev/null 2>&1 || die "go is not on PATH"
[ -f "$doc" ] || die "$doc does not exist"
[ -f "$module_dir/go.mod" ] || die "$module_dir/go.mod does not exist"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The markers: each exactly once, the begin line before the end line.
markers=$(awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
  $0 == b { nb++; bl = NR }
  $0 == e { ne++; el = NR }
  END { if (nb == 1 && ne == 1 && bl < el) print "ok"; else printf "begin x%d, end x%d\n", nb, ne }' "$doc")
[ "$markers" = ok ] || die "$doc must hold the line $BEGIN_MARK and, after it, the line $END_MARK, each once ($markers)"

mod=$(cd "$module_dir" && GOWORK=off GOFLAGS='' go list -m) || die "go list -m failed in $module_dir"

# One tab-separated line per package: path, name, doc, imports, test files, external test files, test imports,
# external test imports, directory, number of non-test files.
tab='{{"\t"}}'
tmpl="{{.ImportPath}}$tab{{.Name}}$tab{{.Doc}}$tab{{join .Imports \" \"}}$tab{{join .TestGoFiles \" \"}}$tab{{join .XTestGoFiles \" \"}}$tab{{join .TestImports \" \"}}$tab{{join .XTestImports \" \"}}$tab{{.Dir}}$tab{{len .GoFiles}}"
(cd "$module_dir" && GOWORK=off GOFLAGS='' GOOS=linux GOARCH=amd64 CGO_ENABLED=0 go list -f "$tmpl" ./... >"$tmp/list" 2>"$tmp/list.err") \
  || die "go list failed in $module_dir: $(cat "$tmp/list.err")"
[ -s "$tmp/list" ] || die "go list found no packages in $module_dir"

# The rows. awk reads each package's test files only to see which services they need.
awk -F'\t' -v mod="$mod" '
function rel(p) { return index(p, mod "/") == 1 ? substr(p, length(mod) + 2) : "" }
function short(p) { return index(p, "internal/") == 1 ? substr(p, 10) : p }
function plural(n) { return n == 1 ? n " file" : n " files" }
{
  n++; path[n] = rel($1); name[n] = $2; doc[n] = $3; imports[n] = $4; tests[n] = $5 " " $6; dir[n] = $9; nfiles[n] = $10
  # who imports me in a test (an external test of myself is my own test)
  split($7 " " $8, ti, " ")
  delete seen
  for (i in ti) {
    r = rel(ti[i])
    if (r == "" || r == path[n] || (path[n] SUBSEP r) in seen) continue
    seen[path[n], r] = 1
    importer_of[r] = importer_of[r] (importer_of[r] == "" ? "" : ", ") short(path[n])
    testimp[n] = testimp[n] " " r
  }
}
END {
  for (k = 1; k <= n; k++) {
    if (nfiles[k] == 0) continue          # a test-only directory has nothing to document
    owns = doc[k]
    sub("^Package " name[k] " ", "", owns); sub("^" name[k] " ", "", owns)
    # a table cell: a pipe would end it, an unterminated comment opener would swallow the rest of the file; the
    # entities render as the characters themselves and leave an existing backslash alone
    gsub(/\|/, "\\&#124;", owns); gsub(/<!--/, "\\&lt;!--", owns)
    deps = ""; split(imports[k], im, " ")
    for (i = 1; i in im; i++) { r = rel(im[i]); if (r != "") deps = deps (deps == "" ? "" : ", ") short(r) }
    if (deps == "") deps = "none"
    # own tests, and what they need
    nt = split(tests[k], tf, " "); pg = (testimp[k] ~ /(^| )internal\/testsupport( |$)/); mq = 0
    for (i = 1; i <= nt; i++) {
      f = dir[k] "/" tf[i]
      while ((getline line < f) > 0) {
        if (index(line, "RYFT_TEST_POSTGRES_URL")) pg = 1
        if (index(line, "RYFT_TEST_AMQP_URL")) mq = 1
      }
      close(f)
    }
    if (nt > 0) {
      need = (pg ? "Postgres" : "") (pg && mq ? ", " : "") (mq ? "RabbitMQ" : "")
      tested = plural(nt) (need == "" ? "" : " (" need ")")
    } else if (importer_of[path[k]] != "") tested = "via " importer_of[path[k]]
    else tested = "none"
    printf "%s\t| `%s` | %s | %s | %s |\n", path[k], path[k], owns, deps, tested
  }
}' "$tmp/list" | LC_ALL=C sort -t "$(printf '\t')" -k1,1 | cut -f2- >"$tmp/rows"
[ -s "$tmp/rows" ] || die "no package with Go files in $module_dir"

{
  echo
  echo "| Package | Owns | Depends on | Tested by |"
  echo "| --- | --- | --- | --- |"
  cat "$tmp/rows"
  echo
  echo "Owns is the first sentence of the package's \`doc.go\`; Depends on lists the direct imports of this module"
  echo "(\`internal/\` left out). Tested by is the number of the package's own test files, with the services the"
  echo "tests need (they skip without \`RYFT_TEST_POSTGRES_URL\` or \`RYFT_TEST_AMQP_URL\`), else the packages whose"
  echo "tests import it. \`make smoke\` and the golden fixtures are not attributed to a package;"
  echo "\`cmd/rabbitmq-topology\` is checked by \`make k8s-validate\`."
  echo
} >"$tmp/table"

# The file with the table between the markers.
awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v t="$tmp/table" '
  $0 == b { print; while ((getline l < t) > 0) print l; skip = 1; next }
  $0 == e { skip = 0 }
  !skip { print }' "$doc" >"$tmp/new"

if [ "$mode" = check ]; then
  # diff: 0 same, 1 differs, anything else is trouble (it must not read as stale)
  drc=0; diff -u "$doc" "$tmp/new" >"$tmp/diff" 2>"$tmp/diff.err" || drc=$?
  if [ "$drc" -gt 1 ]; then die "diff failed ($drc): $(cat "$tmp/diff.err")"; fi
  if [ "$drc" = 1 ]; then
    cat "$tmp/diff" >&2
    echo "pkgmap: the package map in ${doc#"$root"/} is stale; run scripts/pkgmap.sh and commit the result" >&2
    exit 1
  fi
  echo "pkgmap: the package map is current"
  exit 0
fi

cat "$tmp/new" >"$doc"
echo "pkgmap: wrote $(wc -l <"$tmp/rows" | tr -d ' ') packages to ${doc#"$root"/}"
