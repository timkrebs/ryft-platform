#!/usr/bin/env bash
# The committed action of each admission binding as a recording rule (T12-e, D120).
#
#   scripts/admission_intended.sh            write deploy/grafana/alerts/admission-intended.yaml
#   scripts/admission_intended.sh --check    fail when that file differs from what the values give
#
# Source: `actions:` in infra/aws/kubernetes/admission-values.yaml (key: audit|deny; the
# binding is named ryft-<key>). kube-state-metrics cannot read the chart's labels from a
# binding, so the alerts compare the live validation actions with this series:
#   ryft:admission_binding_intended{validatingadmissionpolicybinding="ryft-vso", intended_action="audit"} 1
# `make alerts-check` runs --check, so the file cannot drift from the values it mirrors.
# Load order for a step change: docs/OPERATIONS.md → Admission policy signals.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
values=${ADMISSION_VALUES:-$root/infra/aws/kubernetes/admission-values.yaml}
out=${ADMISSION_INTENDED_OUT:-$root/deploy/grafana/alerts/admission-intended.yaml}
want_bindings=12   # the 12 in AdmissionBindingMissing (deploy/grafana/alerts/ryft.yaml)

render() {
  awk '
    /^actions:/ { inb = 1; next }
    inb && /^[^ #]/ { inb = 0 }
    inb && /^  [a-z0-9-]+:/ { k = $1; sub(/:$/, "", k); print k, $2 }
  ' "$values" | {
    n=0
    cat <<'EOF'
# GENERATED by scripts/admission_intended.sh from `actions:` in
# infra/aws/kubernetes/admission-values.yaml. Do not edit; `make alerts-check` fails when the
# two differ. Each binding's committed action, for AdmissionBindingNotDenying,
# AdmissionBindingDrift and AdmissionBreakGlass (deploy/grafana/alerts/ryft.yaml).
namespace: ryft-admission
groups:
  - name: ryft-admission-intended
    rules:
EOF
    while read -r key action; do
      case "$action" in
        audit | deny) ;;
        *) echo "admission_intended: actions.$key must be audit or deny, got '$action'" >&2; exit 1 ;;
      esac
      n=$((n + 1))
      printf '      - record: ryft:admission_binding_intended\n        expr: vector(1)\n        labels: { validatingadmissionpolicybinding: ryft-%s, intended_action: %s }\n' "$key" "$action"
    done
    if [ "$n" -ne "$want_bindings" ]; then
      echo "admission_intended: found $n actions in $values, the alerts assume $want_bindings (AdmissionBindingMissing)" >&2
      exit 1
    fi
  }
}

case "${1:-}" in
  "")
    tmp=$(mktemp)
    trap 'rm -f "$tmp"' EXIT
    render > "$tmp"
    cp "$tmp" "$out"
    ;;
  --check)
    tmp=$(mktemp)
    trap 'rm -f "$tmp"' EXIT
    render > "$tmp"
    if ! diff -u "$out" "$tmp"; then
      echo "admission_intended: $out is out of date; run scripts/admission_intended.sh" >&2
      exit 1
    fi
    ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac
